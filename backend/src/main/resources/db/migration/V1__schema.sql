-- Stadyum bilet şeması. PostgreSQL ve (PostgreSQL kipinde) H2 ile uyumlu standart SQL.

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(80)   NOT NULL,
    title       VARCHAR(160)  NOT NULL,
    category    VARCHAR(32)   NOT NULL,
    venue       VARCHAR(160)  NOT NULL,
    city        VARCHAR(80)   NOT NULL,
    starts_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    description VARCHAR(1000) NOT NULL,
    hue         INTEGER       NOT NULL,
    CONSTRAINT ux_events_slug UNIQUE (slug)
);

CREATE TABLE seat_holds (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT      NOT NULL REFERENCES events (id),
    -- Ziyaretçiye verilen gizli anahtarın SHA-256 özeti; anahtarın kendisi saklanmaz
    token_hash VARCHAR(64) NOT NULL,
    status     VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_seat_holds_token UNIQUE (token_hash),
    CONSTRAINT ck_seat_holds_status CHECK (status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED'))
);
CREATE INDEX ix_seat_holds_due ON seat_holds (status, expires_at);

CREATE TABLE bookings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(16)  NOT NULL,
    event_id       BIGINT       NOT NULL REFERENCES events (id),
    hold_id        BIGINT       NOT NULL REFERENCES seat_holds (id),
    customer_name  VARCHAR(120) NOT NULL,
    customer_email VARCHAR(254) NOT NULL,
    total_kurus    BIGINT       NOT NULL CHECK (total_kurus >= 0),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_bookings_code UNIQUE (code),
    -- Bir tutma en fazla bir kez satın almaya dönüşebilir
    CONSTRAINT ux_bookings_hold UNIQUE (hold_id)
);

CREATE TABLE event_seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT      NOT NULL REFERENCES events (id),
    block_code  VARCHAR(8)  NOT NULL,
    row_label   VARCHAR(4)  NOT NULL,
    row_index   INTEGER     NOT NULL,
    seat_no     INTEGER     NOT NULL,
    zone        VARCHAR(16) NOT NULL,
    price_kurus BIGINT      NOT NULL CHECK (price_kurus >= 0),
    status      VARCHAR(16) NOT NULL,
    hold_id     BIGINT REFERENCES seat_holds (id),
    booking_id  BIGINT REFERENCES bookings (id),
    CONSTRAINT ux_event_seats_position UNIQUE (event_id, block_code, row_label, seat_no),
    -- Son savunma hattı: uygulama hata yapsa bile koltuk tutarsız bir duruma giremez
    CONSTRAINT ck_event_seats_state CHECK (
        (status = 'AVAILABLE' AND hold_id IS NULL AND booking_id IS NULL)
        OR (status = 'HELD' AND hold_id IS NOT NULL AND booking_id IS NULL)
        OR (status = 'SOLD' AND booking_id IS NOT NULL)
    )
);
CREATE INDEX ix_event_seats_block ON event_seats (event_id, block_code);
CREATE INDEX ix_event_seats_hold ON event_seats (hold_id);
CREATE INDEX ix_event_seats_booking ON event_seats (booking_id);
